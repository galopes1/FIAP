jedi = ["Yoda", "Luke", "Obi-Wan", "Anakin", "Luke", "Darth-Vader"]
print(jedi)

#Remoção do último valor
jedi.pop()
print(jedi)

#Remoção de um valor em posição específica
jedi.pop(0)
print(jedi)

#Remoção de um item específico
jedi.remove("Luke")
print(jedi)

#Apagar a lista toda
jedi.clear()
print(jedi)