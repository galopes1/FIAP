-- CRIAR A SEQUÊNCIA PARA GERAR UM VALOR AUTONUMERICO
CREATE SEQUENCE SQ_TESTE_DDL_SEQUENCE
   INCREMENT BY 1
     START WITH 1
       MAXVALUE 999
        NOCACHE
        NOCYCLE;

-- CRIAÇÃO DE TABELA PARA EXEMPLIFICAR O USO DA SEQUENCE

-- APAGAR A TABELA PARA TESTES
DROP TABLE T_TESTE_DDL_SEQUENCE;

-- CRIAR UMA TABELA PARA TESTES
CREATE TABLE T_TESTE_DDL_SEQUENCE
(
    CD_TESTE_SQ NUMBER(3) 
        DEFAULT SQ_TESTE_DDL_SEQUENCE.NEXTVAL NOT NULL,
    NM_TESTE_SQ     VARCHAR2(30)    NOT NULL
);
-- ADICIONAR A CONSTRAINT CHAVE PRIMARIA
   ALTER TABLE T_TESTE_DDL_SEQUENCE 
ADD CONSTRAINT PK_TESTE_DDL_SEQUENCE 
   PRIMARY KEY (CD_TESTE_SQ);

-- INSERÇÃO DE LINHA UTILIZANDO VALORES AUTONUMÉRICOS 
-- DE FORMA AUTOMÁTICA
-- QUANDO A SEQUÊNCIA É DEFINIDA COMO VALOR DEFAULT PARA O 
-- CAMPO CHAVE PRIMÁRIA
INSERT INTO T_TESTE_DDL_SEQUENCE (NM_TESTE_SQ) 
     VALUES ('TESTE');

-- CONSULTANDO A PSEUDOCOLUNA NEXTVAL
SELECT SQ_TESTE_DDL_SEQUENCE.NEXTVAL FROM DUAL;

-- CONSULTANDO A PSEUDOCOLUNA CURRVAL
SELECT SQ_TESTE_DDL_SEQUENCE.CURRVAL FROM DUAL;

